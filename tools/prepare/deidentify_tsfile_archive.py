#!/usr/bin/env python3
"""Remove direct identifiers from a complete QAR TsFile archive.

Private mapping/audit output MUST remain separate from the distributable folder.
Only external names and internal device metadata change; numeric chunks and
existing relative timestamps are copied and hash-checked for every file.
This preserves benchmark signals and does not guarantee anonymity against an
attacker who possesses matching external flight records or sensor traces.
"""
import argparse
import collections
import csv
import hashlib
import json
import os
import struct
import subprocess
import zipfile
from datetime import datetime, timedelta
from pathlib import Path

from prepare_tsfile_compact_custom_conditions import DATASET_RE, time_key_from_source


def sha256(path):
    digest = hashlib.sha256()
    with path.open('rb') as handle:
        for block in iter(lambda: handle.read(8 * 1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def csv_text(rows):
    import io
    out = io.StringIO(newline='')
    writer = csv.DictWriter(out, fieldnames=list(rows[0]), lineterminator='\n')
    writer.writeheader()
    writer.writerows(rows)
    return out.getvalue()


def neutral_zip_metadata(info):
    """Allow only neutral dates and newly required ZIP64 size/offset fields.

    ZIP64 bookkeeping is necessary for archives beyond 4 GiB; its offsets are
    generated by the new ZIP writer and carry no original identifying fields.
    """
    if info.date_time != (1980, 1, 1, 0, 0, 0) or info.comment:
        return False
    extra, seen = info.extra, set()
    while extra:
        if len(extra) < 4:
            return False
        field, length = struct.unpack_from('<HH', extra)
        if field != 1 or field in seen or len(extra) < length + 4:
            return False
        seen.add(field)
        payload, extra = extra[4:4+length], extra[4+length:]
        expected = b''.join(struct.pack('<Q', value) for value in
                            [info.file_size, info.compress_size] if value >= 0xffffffff)
        # Some Java ZIP writers conservatively switch offsets at signed 2 GiB.
        if info.header_offset >= 0x7fffffff:
            expected += struct.pack('<Q', info.header_offset)
        if payload != expected:
            return False
    return True


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--input-zip', type=Path, required=True)
    p.add_argument('--output-dir', type=Path, required=True)
    p.add_argument('--private-dir', type=Path, required=True)
    p.add_argument('--iotdb-lib', type=Path, required=True)
    p.add_argument('--threads', type=int, default=4)
    p.add_argument('--limit-per-group', type=int, default=0, help='Pilot only; 0 processes the complete input')
    args = p.parse_args()
    os.umask(0o077)
    source, output, private, lib = (x.resolve() for x in
                                  [args.input_zip, args.output_dir, args.private_dir, args.iotdb_lib])
    if output == private or private.is_relative_to(output) or output.is_relative_to(private):
        raise ValueError('Public and private output directories must be separate, not nested')
    if not source.is_file() or not lib.is_dir():
        raise FileNotFoundError('Input archive or TsFile library directory is missing')
    if not 1 <= args.threads <= 8 or args.limit_per_group < 0:
        raise ValueError('Invalid thread/sample limit')
    if output.exists() or private.exists():
        raise FileExistsError('Use new output and private directories to avoid overwrites')
    output.mkdir(parents=True)
    private.mkdir(parents=True)
    repo = Path(__file__).resolve().parents[2]
    java_src = repo/'tools/tsfile/TsFileDeidentify.java'
    classes, work = private/'classes', private/'temporary'
    classes.mkdir()
    work.mkdir()
    by_dataset = collections.defaultdict(list)
    with zipfile.ZipFile(source) as archive:
        for entry in archive.infolist():
            if entry.is_dir():
                continue
            match = DATASET_RE.fullmatch(entry.filename)
            if not match or any(ch in entry.filename for ch in '\r\n\t'):
                raise ValueError('Unexpected archive layout; review unrecognized input entries privately')
            dataset, label, _ = match.groups()
            by_dataset[dataset].append((time_key_from_source(entry.filename), entry.filename, label))
    mapping = []
    selected_counts = collections.Counter()
    dataset_sort = lambda s: tuple(int(x) for x in s.removeprefix('dataset').split('-'))
    with (private/'plan_private.tsv').open('w', encoding='utf-8', newline='') as plan:
        for dataset in sorted(by_dataset, key=dataset_sort):
            for ordinal, (old_time, old_member, label) in enumerate(sorted(by_dataset[dataset]), 1):
                if args.limit_per_group and selected_counts[(dataset, label)] >= args.limit_per_group:
                    continue
                selected_counts[(dataset, label)] += 1
                # Existing cache parsing reduces dates to day-level keys.
                # Give each ordinal its own artificial day so exact old order,
                # including cross-label ties, survives that parser unchanged.
                date = datetime(2000, 1, 1) + timedelta(days=ordinal-1)
                filename = f'sample_{date:%Y-%m-%d}_00-00-00_{ordinal:06d}.tsfile'
                member = f'tsfile_datasets/{dataset}_tsfile/{label}/{filename}'
                device = f'sample_{ordinal:06d}'
                plan.write(f'{old_member}\t{member}\t{device}\n')
                mapping.append(dict(original_member=old_member, public_member=member,
                                    dataset=dataset, label=label, order=ordinal,
                                    original_time_key=old_time, synthetic_time_key=time_key_from_source(member)))
    if not mapping:
        raise ValueError('No input flights found')
    (private/'source_mapping_private.csv').write_text(csv_text(mapping), encoding='utf-8')
    summary = dict(profile='numeric_signal_preserving_direct_identifier_removal_v1',
                   samples=len(mapping), datasets=sorted(by_dataset, key=dataset_sort),
                   counts={f'{d}/{label}': n for (d, label), n in sorted(selected_counts.items())},
                   pilot_limit_per_group=args.limit_per_group, complete=False)
    (private/'status.json').write_text(json.dumps(summary, indent=2), encoding='utf-8')
    subprocess.run(['javac', '-encoding', 'UTF-8', '-cp', str(lib/'*'), '-d', str(classes), str(java_src)], check=True)
    partial = output/'tsfile_datasets_deidentified.partial.zip'
    audit = private/'all_file_checks_private.tsv'
    subprocess.run(['java', '-Xmx2g', '-Duser.timezone=UTC', '-XX:ActiveProcessorCount='+str(args.threads),
                    '-cp', os.pathsep.join([str(classes), str(lib/'*')]), 'TsFileDeidentify',
                    str(source), str(private/'plan_private.tsv'), str(partial), str(audit),
                    str(work), str(args.threads)], check=True)
    with audit.open(encoding='utf-8') as handle:
        checks = list(csv.DictReader(handle, delimiter='\t'))
    if len(checks) != len(mapping) or {r['public_member'] for r in checks} != {r['public_member'] for r in mapping}:
        raise RuntimeError('Incomplete output audit')
    public_rows = [dict(dataset=r['dataset'], label=r['label'], order=r['order'], public_member=r['public_member']) for r in mapping]
    readme = f'''# QAR TsFile data with direct identifiers removed

This archive contains {len(mapping):,} flights from {len(by_dataset)} datasets.
All original input flights are retained unless this is explicitly marked as a pilot.
Datasets 9 and 12 are present in the full archive but excluded by the nine-dataset main launchers.

Replaced: original filenames, internal TsFile device identifiers, original ZIP modification times.
Removed: original device/schema-index metadata, bloom filters and file properties; new metadata is generated.
No aircraft registrations, airline/flight numbers, routes, calendar dates or maintenance descriptions
are copied into public names or manifests. The private mapping is not part of this package.

Preserved: dataset/0-or-1 labels, original order within each dataset (including cross-label ties),
measurement names, numeric value chunks, null layouts, flight phases and within-flight relative ticks.
Every file's schema and compressed time/value chunks are SHA256-checked against its source.
Relative nanosecond ticks and source-record offsets are retained. The tool rejects a
flight span beyond 72 hours, a tick counter beyond one year and unexpected sampling scales;
actual modern calendar/epoch timestamps therefore fail this profile instead of being copied.

The dates in filenames are ARTIFICIAL ORDINAL CODES starting at 2000-01-01.
One artificial day represents one successive available flight. They are not actual flight dates,
and cannot be used to estimate between-flight gaps. Use `order` for chronological benchmark splitting.

This signal-preserving release removes direct identifiers. Raw duration and sensor patterns remain;
it is not a guarantee against linkage to external flight records. No privacy noise is added.
Dataset13 still reflects the available archive population, not a recovered exact paper subset.

Use with the public code by setting ZIP_PATH to this ZIP and IOTDB_LIB to installed TsFile JARs.
Caches are generated locally; no prebuilt caches or old Parquet/CSV archives are required.
Code licenses do not automatically license this dataset; use the data provider's terms.
Pilot limit per dataset/label group: {args.limit_per_group} (0 means complete input).
'''
    neutral_date = (1980, 1, 1, 0, 0, 0)
    with zipfile.ZipFile(partial, 'a', compression=zipfile.ZIP_DEFLATED, compresslevel=1) as archive:
        for name, body in [('README_DEIDENTIFICATION.md', readme),
                           ('MANIFEST_PUBLIC.csv', csv_text(public_rows)),
                           ('SUMMARY_PUBLIC.json', json.dumps({**summary, 'complete': True}, indent=2))]:
            entry = zipfile.ZipInfo(name, date_time=neutral_date)
            entry.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(entry, body)
    print('VERIFY_ZIP_CRC', flush=True)
    with zipfile.ZipFile(partial) as archive:
        bad = archive.testzip()
        if bad:
            raise RuntimeError('ZIP CRC verification failed')
        assert len([i for i in archive.infolist() if i.filename.endswith('.tsfile')]) == len(mapping)
        assert all(neutral_zip_metadata(i) for i in archive.infolist())
        assert not archive.comment
    final = output/'tsfile_datasets_deidentified.zip'
    partial.replace(final)
    digest = sha256(final)
    (output/'SHA256SUMS.txt').write_text(f'{digest}  {final.name}\n', encoding='utf-8')
    (output/'README_DEIDENTIFICATION.md').write_text(readme, encoding='utf-8')
    summary.update(complete=True, zip_bytes=final.stat().st_size, sha256=digest,
                   all_numeric_time_chunks_identical=True, all_internal_identifiers_rebuilt=True,
                   all_zip_crc_passed=True)
    (output/'VERIFICATION_PUBLIC.json').write_text(json.dumps(summary, indent=2), encoding='utf-8')
    (private/'status.json').write_text(json.dumps(summary, indent=2), encoding='utf-8')
    work.rmdir()
    print(json.dumps(summary), flush=True)


if __name__ == '__main__':
    main()
